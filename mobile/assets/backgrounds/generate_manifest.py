import os
import re
from PIL import Image

files = sorted(f for f in os.listdir(".") if f.startswith("bg-") and f.endswith(".jpg"))

entries = []
for f in files:
    img = Image.open(f).convert("L").resize((32, 32))
    pixels = list(img.getdata())
    luminance = sum(pixels) / len(pixels)
    opacity = max(0.28, min(0.62, 0.62 - (luminance / 255) * 0.5))
    m = re.match(r"bg-([a-z]+)-(\d+)\.jpg", f)
    category = m.group(1)
    entries.append((f, category, round(opacity, 2)))

lines = []
lines.append("// Auto-generated by assets/backgrounds/generate_manifest.py — do not hand-edit.")
lines.append("// washOpacity is derived from each photo's measured average luminance (computed")
lines.append("// once at curation time, not at runtime) so every photo ends up similarly muted")
lines.append('// behind content regardless of how light or dark the source photo is — the "auto')
lines.append('// tone adjustment" the background pool needs for legibility.')
lines.append("export interface PageBackgroundEntry {")
lines.append("  source: number;")
lines.append("  category: string;")
lines.append("  washOpacity: number;")
lines.append("}")
lines.append("")
lines.append("export const PAGE_BACKGROUNDS: PageBackgroundEntry[] = [")
for f, category, opacity in entries:
    lines.append(
        f'  {{ source: require("../../assets/backgrounds/{f}"), category: "{category}", washOpacity: {opacity} }},'
    )
lines.append("];")
lines.append("")

with open("../../src/components/pageBackgroundManifest.ts", "w") as out:
    out.write("\n".join(lines))

print(f"Wrote {len(entries)} entries")
